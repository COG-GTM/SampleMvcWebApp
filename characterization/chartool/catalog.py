"""CATALOG.md: one row per scenario with its docs/as-is finding ids and checklist tests, plus CT coverage.

Regenerate with `python -m chartool.catalog` (run from characterization/); tests fail when it is stale.
"""
import re
from pathlib import Path

from .scenarios import load_all

CHAR = Path(__file__).resolve().parents[1]
CHECKLIST = ["CT-%02d" % i for i in range(1, 39)]
NA_RE = re.compile(r"^\| (CT-\d\d) \| N/A", re.M)


def not_applicable(readme_text):
    """CT ids that characterization/README.md declares not applicable (table rows '| CT-nn | N/A ...')."""
    return set(NA_RE.findall(readme_text))


def coverage(scenarios):
    cov = {ct: [] for ct in CHECKLIST}
    for s in scenarios:
        for ct in s.get("tests") or []:
            cov.setdefault(ct, []).append(s["name"])
    return cov


def render(scenarios, readme_text):
    na = not_applicable(readme_text)
    lines = ["# Scenario catalogue (generated by `python -m chartool.catalog`; do not edit)", "",
             "Finding ids refer to `docs/as-is/hidden-behavior.md`; test ids to the characterization test list in",
             "`docs/as-is/migration-risks.md` section 2. Transcripts: `transcripts/<group>/<scenario>.json`.", "",
             "%d scenarios." % len(scenarios), "",
             "| Scenario | Group | Channel | Finding | Tests | Oddity |", "|---|---|---|---|---|---|"]
    for s in sorted(scenarios, key=lambda s: (s["group"], s["name"])):
        lines.append("| `%s` | %s | %s | %s | %s | %s |" % (s["name"], s["group"], s["channel"], ", ".join(s["finding"]),
                                                          ", ".join(s.get("tests") or []), "yes" if s.get("oddity") else ""))
    lines += ["", "## Checklist coverage (CT-01..CT-38)", "", "| Test | Transcripts |", "|---|---|"]
    for ct, names in coverage(scenarios).items():
        cell = ", ".join("`%s`" % n for n in sorted(names)) or ("not applicable, see README.md" if ct in na else "**MISSING**")
        lines.append("| %s | %s |" % (ct, cell))
    return "\n".join(lines) + "\n"


def main():
    text = render(load_all(CHAR / "scenarios"), (CHAR / "README.md").read_text(encoding="utf-8"))
    (CHAR / "CATALOG.md").write_text(text, encoding="utf-8", newline="\n")
    print("wrote %s" % (CHAR / "CATALOG.md"))


if __name__ == "__main__":
    main()
