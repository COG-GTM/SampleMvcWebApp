#!/usr/bin/env python3
"""Render docs/proof/s6-e2e-cutover.md from build/e2e/{legacy,migrated}.json and build/cutover/diff.json."""
import json
import os
import sys

ROOT = os.path.dirname(os.path.dirname(os.path.dirname(os.path.abspath(__file__))))


def load(p):
    p = os.path.join(ROOT, p)
    return json.load(open(p)) if os.path.exists(p) else None


def e2e_section(name, r):
    if not r:
        return ['_%s: not run_' % name, '']
    out = ['### %s (head `%s`, as-of %s)' % (name, r['head'][:10], r['asOf']), '',
           'Health: %s. HB-01: %s.' % (', '.join('%s %s' % kv for kv in r['health'].items()),
                                       r.get('hb01', {}).get('status', '?')), '',
           '| Category | Pass | Fail | n/a |', '|---|---|---|---|']
    for k, v in r['summary'].items():
        out.append('| %s | %d | %d | %d |' % (k, v['pass'], v['fail'], v['na']))
    tot = [sum(v[x] for v in r['summary'].values()) for x in ('pass', 'fail', 'na')]
    out.append('| **total** | **%d** | **%d** | %d |' % tuple(tot))
    d = r.get('drift')
    if d:
        out += ['', 'Drift under load: %(ops)s ops, %(workers)s workers, %(samples)s samples over %(seconds)ss; '
                '**max raw seat drift %(maxRawDrift)s, max unexplained %(maxUnexplainedDrift)s**, max duplicate waitlist '
                'positions %(maxDupWaitlistPositions)s.' % d, '', 'Load mix: `%s`' % json.dumps(d['stats'])]
    fails = [c for c in r['checks'] if not c['ok'] and not c['na']]
    if fails:
        out += ['', 'Failures:'] + ['- [%s] %s: `%s`' % (c['category'], c['name'], json.dumps(c['detail'], default=str)[:300]) for c in fails]
    pt = r.get('parity_table')
    if pt:
        out += ['', '<details><summary>Portal vs partner parity trace (same scenario on each channel)</summary>', '',
                '| Step | Portal outcome | Partner outcome | Portal seats | Partner seats | Portal waitlist | Partner waitlist | Differs |',
                '|---|---|---|---|---|---|---|---|']
        for x in pt:
            a, b = x['portal'], x['partner']
            out.append('| %s | %s | %s | %s | %s | %s | %s | %s |' % (x['step'], a['outcome'], b['outcome'], a['seats'], b['seats'],
                                                                   a['waitlist'], b['waitlist'], ', '.join(x['differs']) or '-'))
        out += ['', '</details>']
    return out + ['']


def main():
    L, M, D = load('build/e2e/legacy.json'), load('build/e2e/migrated.json'), load('build/cutover/diff.json')
    md = ['# Phase 3 (S6): end-to-end suite and cutover rehearsal', '',
          'Generated by `python scripts/e2e/report.py` from the runs below. Raw JSON: `build/e2e/*.json`, `build/cutover/*.json` '
          '(not committed).', '', '## How to run', '', '```powershell',
          '# legacy estate (estate/legacy-baseline worktree) or migrated stack must be up; see scripts/run-legacy.ps1',
          'powershell -ExecutionPolicy Bypass -File scripts/mixed-traffic.ps1 -E2E -Target legacy',
          'powershell -ExecutionPolicy Bypass -File scripts/e2e/cutover-rehearsal.ps1 -LegacyRoot ../ad-legacy   # leaves the migrated stack up',
          'powershell -ExecutionPolicy Bypass -File scripts/mixed-traffic.ps1 -E2E -Target migrated',
          'python scripts/e2e/report.py', '```', '', '## E2E suite', '']
    md += e2e_section('Legacy estate', L) + e2e_section('Migrated stack', M)
    md += ['## Cutover rehearsal', '']
    if not D:
        md += ['_not run_']
    else:
        md += ['Legacy worktree `%s`, migrated `%s`, as-of %s. Inputs chosen identically on both sides: %s. **Zero drift: %s.**'
               % (D['legacyHead'][:10], D['migratedHead'][:10], D['asOf'], D['inputsEqual'], D['zeroDrift']), '',
               'Baseline (production copy vs scheduling-service import, before the workload): ' +
               ', '.join('%s %d/%d identical' % (k, v['identical'], v['legacyRows']) for k, v in D['baseline'].items()), '',
               '| Table | Legacy rows | Migrated rows | Identical | Only legacy | Only migrated | Changed | Unexplained drift |',
               '|---|---|---|---|---|---|---|---|']
        for k, v in D['tables'].items():
            md.append('| %s | %d | %d | %d | %d | %d | %d | **%d** |' % (k, v['legacyRows'], v['migratedRows'], v['identical'],
                      v['onlyLegacy'], v['onlyMigrated'], v['changed'], D['unexplained'][k]))
        md += ['', 'Operation outcomes compared op by op: %d ops, %d mismatches.' % (len(D['outcomes']), len(D['outcomeMismatches'])), '']
        if D['hb01Justified']:
            md += ['### Intentionally removed legacy defect: HB-01', '',
                   'Each row below differs only in `SeatsAvailable`, by exactly the number of PARTNER bookings inserted BOOKED '
                   'on that session (legacy took 2 seats each: booking-api decrement + trg_Booking_SeatSync; scheduling-service, '
                   'the single writer, takes 1).', '', '| SessionId | Legacy seats | Migrated seats | Partner BOOKED inserts |', '|---|---|---|---|']
            md += ['| %(sessionId)s | %(legacySeats)s | %(migratedSeats)s | %(partnerBookedInserts)s |' % r for r in D['hb01Justified']]
            md.append('')
        else:
            md += ['No intentionally-removed defect showed up: the migrated stack ran with HB-01 kept, so no row needed justification.', '']
        md += ['<details><summary>Workload outcomes (legacy vs migrated)</summary>', '', '| Operation | Legacy | Migrated |', '|---|---|---|']
        md += ['| %s | %s | %s |' % (o['op'], o['legacy'], o['migrated']) for o in D['outcomes']]
        md += ['', '</details>', '']
        bad = {k: v for k, v in D['details'].items() if v}
        if bad:
            md += ['### Diff rows', ''] + ['- %s: `%s`' % (k, json.dumps(x, default=str)[:400]) for k, v in bad.items() for x in v[:20]] + ['']
    md += [open(os.path.join(ROOT, 'scripts', 'e2e', 'NORMALIZATION.md')).read()]
    out = os.path.join(ROOT, 'docs', 'proof', 's6-e2e-cutover.md')
    os.makedirs(os.path.dirname(out), exist_ok=True)
    open(out, 'w', newline='\n').write('\n'.join(md) + '\n')
    print(out)


if __name__ == '__main__':
    sys.exit(main())
