package com.northwind.assessment.scheduling.reconciliation;

import com.northwind.assessment.scheduling.reconciliation.ReconciliationService.Mismatch;
import com.northwind.assessment.scheduling.reconciliation.ReconciliationService.Report;
import java.util.List;

/** Markdown for {@code reports/reconciliation-<timestamp>.md}. */
final class ReportFormatter {

    private ReportFormatter() {
    }

    static String markdown(Report r) {
        StringBuilder sb = new StringBuilder();
        sb.append("# Reconciliation report: Scheduling vs AssessmentDelivery\n\n");
        sb.append("Generated by scheduling-service `reconcile` (MBA-3823) at ").append(r.ranAt()).append(".\n\n");
        sb.append("| Metric | Value |\n|---|---|\n");
        sb.append("| Sessions compared | ").append(r.sessionsCompared()).append(" |\n");
        sb.append("| Bookings compared | ").append(r.bookingsCompared()).append(" |\n");
        sb.append("| Legacy-only sessions (missing in Scheduling, counted as mismatches) | ").append(r.legacyOnlySessions()).append(" |\n");
        sb.append("| **Mismatches** | **").append(r.mismatchCount()).append("** |\n");
        sb.append("| **db/checks/seat-drift.sql rows** | **").append(r.seatDriftRows().size()).append("** |\n");
        var relay = r.relay();
        sb.append("| Outbox events relayed / pending | ").append(relay.relayedEvents()).append(" / ").append(relay.pendingEvents()).append(" |\n");
        sb.append("| Relay lag p95 / max (ms) | ").append(relay.p95LagMs()).append(" / ").append(relay.maxLagMs()).append(" |\n");
        if (relay.lastError() != null) {
            sb.append("| Relay last error | ").append(cell(relay.lastError())).append(" |\n");
        }
        sb.append("\nCompared per session: Capacity, SeatsAvailable (Scheduling: max(0, Capacity - BOOKED - ATTENDED)), ")
                .append("BOOKED / ATTENDED / WAITLISTED counts, accommodation seats used (ET25/ET50 holding a seat), ")
                .append("and per booking: SessionId, Status, AccommodationCode.\n\n");
        sb.append("## Mismatches\n\n");
        if (r.mismatches().isEmpty()) {
            sb.append("None.\n\n");
        } else {
            sb.append("| Session | Booking | Field | Scheduling | AssessmentDelivery |\n|---|---|---|---|---|\n");
            List<Mismatch> shown = r.mismatches().subList(0, Math.min(ReconciliationService.MAX_LISTED, r.mismatches().size()));
            for (Mismatch m : shown) {
                sb.append("| ").append(m.sessionId() == null ? "" : m.sessionId()).append(" | ")
                        .append(m.bookingRef() == null ? "" : m.bookingRef()).append(" | ").append(m.field()).append(" | ")
                        .append(cell(m.scheduling())).append(" | ").append(cell(m.legacy())).append(" |\n");
            }
            if (r.mismatches().size() > shown.size()) {
                sb.append("\n(").append(r.mismatches().size() - shown.size()).append(" more not listed)\n");
            }
            sb.append('\n');
        }
        sb.append("## db/checks/seat-drift.sql (AssessmentDelivery)\n\n");
        sb.append(r.seatDriftRows().size()).append(" row(s).\n\n");
        if (!r.seatDriftRows().isEmpty()) {
            sb.append("| ").append(String.join(" | ", r.seatDriftColumns())).append(" |\n");
            sb.append("|").append("---|".repeat(r.seatDriftColumns().size())).append('\n');
            for (List<String> row : r.seatDriftRows()) {
                sb.append("| ").append(String.join(" | ", row.stream().map(ReportFormatter::cell).toList())).append(" |\n");
            }
        }
        return sb.toString();
    }

    private static String cell(String s) {
        return s == null ? "" : s.replace("|", "\\|").replace("\n", " ");
    }
}
